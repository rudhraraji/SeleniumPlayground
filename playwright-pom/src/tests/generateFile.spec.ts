import { expect, test } from '../fixtures/test';
import GenerateFilePage from '../pages/GenerateFilePage';

test('File Download Demo › generates and downloads a text file', async ({ page }) => {
  const generateFilePage = new GenerateFilePage(page);
  await generateFilePage.open();

  await expect(generateFilePage.generateButton).toBeDisabled();
  await generateFilePage.enterText('Generated by Playwright');
  await expect(generateFilePage.generateButton).toBeEnabled();
  await generateFilePage.generateButton.click();
  await expect(generateFilePage.downloadLink).toBeVisible();
  await expect(generateFilePage.downloadLink).toHaveAttribute('download', 'Lambdainfo.txt');

  const downloadPromise = page.waitForEvent('download');
  await generateFilePage.downloadLink.click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('Lambdainfo.txt');
});
